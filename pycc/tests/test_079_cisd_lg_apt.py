"""
CISD length-gauge atomic polar tensors - pycc.apt(pycc.CIderiv(ci)) facade. 
dipole_derivatives() is inherited from CorrelatedDerivs (the 2n+1 route), 
driven by CIderiv's density hooks - no CISD-specific APT code.

Reference generated by the standalone validated CISD-VCD
implementation (cisd_vcd.py / cisd_apt_lg.py / cisd_analytic_hessian.py;
A. Krishnan, June 2026), at the geometry below.  That implementation was
itself validated independently: the analytic Hessian against Psi4/Gaussian
finite differences, the AATs against the determinant-based apyib
reference (B. Shumberger; ~1e-11 a.u.), and the LG-APT (Z-vector route)
against finite differences of the analytic dipole.  The CIwfn port
reproduces these values to ~1e-10; the test tolerance absorbs the
printed precision of the reference.  The references are TOTAL tensors, so
the tests exercise the full facade decomposition (nuclear + HF reference +
CISD correlation).  Spatial orbitals.  Structured to mirror test_068_mp2_apt: all-electron and
frozen-core in one module, a local wavefunction factory, and correlation-APT components keyed by
the psi4 freeze_core string.
"""

