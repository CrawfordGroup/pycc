def _cideriv_water(freeze_core='false', basis='6-31G'):
    """CISD derivative driver on water (no near-degenerate occupied orbitals)."""
    psi4.core.clean()
    psi4.core.clean_options()
    psi4.geometry(GAUGE_WATER)
    psi4.set_options({'basis': basis, 'scf_type': 'pk', 'freeze_core': freeze_core,
                      'e_convergence': 1e-13, 'd_convergence': 1e-13})
    _, wfn = psi4.energy('scf', return_wfn=True)
    ci = pycc.CIwfn(wfn, model='CISD', orbital_basis='spatial')
    ci.solve_ci(e_conv=1e-13, r_conv=1e-13, maxiter=250)
    return pycc.CIderiv(ci)

def test_cisd_hessian_vs_reference(cisd_h2o2):
    """The facade total (nuclear repulsion + HF reference + CISD correlation)
    reproduces the standalone validated reference, every element."""
    H = np.asarray(pycc.hessian(pycc.CIderiv(cisd_h2o2())).total)
    assert np.max(np.abs(H - HESS_REF)) < 1e-8, np.max(np.abs(H - HESS_REF))


def test_cisd_hessian_gradfd():
    """All-electron correlation-Hessian columns vs their frozen references (validated once
    against a 7-point FD of the analytic gradient to ~2e-12)."""
    H = np.asarray(_cideriv().hessian().correlation)
    for (atom, cart), ref in HESS_COL['false'].items():
        j = atom * 3 + cart
        assert np.max(np.abs(H[:, j] - ref)) < 1e-9, (atom, cart, np.max(np.abs(H[:, j] - ref)))


def test_cisd_hessian_gradfd_frozen_core():
    """Frozen-core correlation-Hessian columns vs their frozen references (validated once against
    the same 7-point gradient FD).  This is the nuclear-nuclear core<->active response: the
    frozen-core perturbed Z-vector for a nuclear perturbation, twice over."""
    cd = _cideriv(freeze_core='true')
    assert cd.ci.nfzc == 2, cd.ci.nfzc
    H = np.asarray(cd.hessian().correlation)
    for (atom, cart), ref in HESS_COL['true'].items():
        j = atom * 3 + cart
        assert np.max(np.abs(H[:, j] - ref)) < 1e-9, (atom, cart, np.max(np.abs(H[:, j] - ref)))


def test_cisd_hessian_symmetry_sum_rule(cisd_h2o2):
    """The total Hessian is symmetric and
    translationally invariant (sum over the second atom vanishes); the
    correlation block obeys both on its own."""
    comp = pycc.hessian(pycc.CIderiv(cisd_h2o2()))
    for H in (np.asarray(comp.total), np.asarray(comp.correlation)):
        assert np.max(np.abs(H - H.T)) < 1e-9
        assert np.max(np.abs(H.reshape(4, 3, 4, 3).sum(axis=2))) < 1e-9


def test_cisd_hessian_symmetry_sum_rule_frozen_core(cisd_h2o2):
    """Frozen-core counterpart of the symmetry / translational sum rule above. Reference-free: the
    correlation Hessian must stay symmetric and translationally invariant with a frozen core."""
    comp = pycc.hessian(pycc.CIderiv(cisd_h2o2(freeze_core=True)))
    H = np.asarray(comp.correlation)
    assert np.max(np.abs(H - H.T)) < 1e-9, np.max(np.abs(H - H.T))
    natom = H.shape[0] // 3
    blocks = H.reshape(natom, 3, natom, 3).sum(axis=2)
    assert np.max(np.abs(blocks)) < 1e-8, np.max(np.abs(blocks))


def test_cisd_hessian_perturbed_mo_gauge_invariance():
    """The correlation Hessian is invariant to the perturbed-MO gauge (non-canonical default vs the
    canonical dependent-pair route), all-electron and frozen-core."""
    for fc in ('false', 'true'):
        nc = np.asarray(_cideriv_water(fc).hessian().correlation)
        cd = _cideriv_water(fc)
        cd._gauge_override = 'canonical'
        ca = np.asarray(cd.hessian().correlation)
        assert np.max(np.abs(nc - ca)) < 1e-9, (fc, np.max(np.abs(nc - ca)))
