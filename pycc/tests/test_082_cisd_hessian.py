def _geom(coords):
    s = "units bohr\nsymmetry c1\nno_com\nno_reorient\n"
    for sym, xyz in zip(SYM, coords):
        s += f"{sym} {xyz[0]:.10f} {xyz[1]:.10f} {xyz[2]:.10f}\n"
    return s


def _cideriv(coords=BASE, freeze_core='false', basis='sto-3g'):
    """Converged spatial CISD derivative driver.  Mirrors test_069's ``_mpwfn``; no
    ``orbital_basis`` knob because the CIderiv path is spatial-only."""
    psi4.core.clean()
    psi4.core.clean_options()
    psi4.geometry(_geom(coords))
    psi4.set_options({'basis': basis, 'scf_type': 'pk', 'freeze_core': freeze_core,
                      'e_convergence': 1e-13, 'd_convergence': 1e-13})
    _, wfn = psi4.energy('scf', return_wfn=True)
    ci = pycc.CIwfn(wfn, model='CISD', orbital_basis='spatial')
    ci.solve_ci(e_conv=1e-13, r_conv=1e-13, maxiter=250)
    return pycc.CIderiv(ci)


def _gradfd_col(atom, cart, freeze_core='false', h=0.002):
    """Regeneration recipe for HESS_COL (not run in the tests): one correlation-Hessian column
    (3*natom,) via a 7-point O(h^6) FD of the analytic correlation GRADIENT - the first-order
    Z-vector gradient, independent of the 2n+1 Hessian code the frozen columns validate."""
    def g(delta):
        c = BASE.copy()
        c[atom, cart] += delta
        return np.asarray(_cideriv(c, freeze_core).gradient().correlation)
    return ((-g(-3 * h) + 9 * g(-2 * h) - 45 * g(-h)
             + 45 * g(h) - 9 * g(2 * h) + g(3 * h)) / (60 * h)).reshape(-1)


